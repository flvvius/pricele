import json, re, sys, urllib.request

API = "https://api.bls.gov/publicAPI/v1/timeseries/data/"
WAGE = "CES0500000008"
FIRST, LAST = 1980, 2025

src = open("data/then-and-now.ts").read()
meta = re.findall(r'"id": "([^"]+)",\s*"name": "([^"]+)",\s*"unit": "([^"]+)",\s*"blsItem": "([^"]+)",\s*"series": "([^"]+)"', src)
series = [m[4] for m in meta] + [WAGE]

monthly = {s: {} for s in series}
for start in range(FIRST, LAST + 1, 10):
    body = json.dumps({"seriesid": series, "startyear": str(start), "endyear": str(min(start + 9, LAST))}).encode()
    req = urllib.request.Request(API, body, {"Content-Type": "application/json"})
    res = json.load(urllib.request.urlopen(req))
    if res["status"] != "REQUEST_SUCCEEDED":
        sys.exit(res)
    for s in res["Results"]["series"]:
        for x in s["data"]:
            if x["period"].startswith("M") and x["period"] != "M13":
                try:
                    monthly[s["seriesID"]].setdefault(int(x["year"]), []).append(float(x["value"]))
                except ValueError:
                    pass

def annual(sid):
    return {y: round(sum(v) / len(v), 2) for y, v in sorted(monthly[sid].items()) if len(v) >= 10}

items = [{"id": i, "name": n, "unit": u, "blsItem": b, "series": s, "prices": annual(s)} for i, n, u, b, s in meta]
print("// GENERATED by scripts/price-history/fetch.py from the BLS public API (v1),")
print("// Average Price Data (APU0000*, U.S. city average) and average hourly earnings of")
print(f"// production and nonsupervisory employees ({WAGE}), {FIRST}-{LAST}. Each value is the")
print("// mean of that year's monthly figures; years with fewer than 10 months are left out.")
print("// BLS data is a U.S. federal government work and in the public domain. Do not hand-edit.")
print('import type { ThenNowItem } from "@/lib/thenandnow";\n')
print(f'export const WAGE_SERIES = "{WAGE}";\n')
print("export const HOURLY_WAGE: Record<number, number> = " + json.dumps(annual(WAGE), indent=2) + ";\n")
print("export const HISTORY_ITEMS: ThenNowItem[] = " + json.dumps(items, indent=2) + ";")
